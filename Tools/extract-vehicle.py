#!/usr/bin/env python3
"""Extract ControlVehicle + ControlWheel authored geometry from Frontier's
EngineContent/GeometryArchives/*.inl (Frontier commit 319e5532d2f0f1ca59e6e5fb6997085928aadec2,
branch arena/4f07c82a-frontier) into src/control-vehicle-data.js.

Usage: python3 Tools/extract-vehicle.py [path-to-Frontier-checkout]
The .inl files are GENERATED by Frontier's CarModelling/Tools/SceneToHeader.py from
ControlVehicle.blend -- this script only re-encodes the same authored arrays for the web;
it does not invent or simplify geometry.
"""
import re, sys, json, pathlib

root = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path('/tmp/frontier')
arch = root / 'EngineContent/GeometryArchives'

def parse_array(text, name):
    m = re.search(rf'{name}\[\]\s*=\s*\{{(.*?)\}};', text, re.S)
    if not m: raise SystemExit(f'missing {name}')
    return [float(x.rstrip('f')) if not re.fullmatch(r'-?\d+', x.strip()) else int(x) for x in m.group(1).replace('\n',' ').split(',') if x.strip()]

def parse_ints(text, name):
    m = re.search(rf'{name}\[\]\s*=\s*\{{(.*?)\}};', text, re.S)
    if not m: raise SystemExit(f'missing {name}')
    return [int(x.strip().rstrip('u')) for x in m.group(1).replace('\n',' ').split(',') if x.strip()]

def fmt(arr, per=12):
    out=[]
    for i in range(0, len(arr), per):
        out.append('  ' + ','.join(repr(v) for v in arr[i:i+per]) + ',')
    return '\n'.join(out)

veh = (arch/'ControlVehicleStructure.inl').read_text()
wheel = (arch/'ControlWheelStructure.inl').read_text()
data = {
 'vehiclePositions': parse_array(veh, 'kPositions'),
 'vehicleTriangles': parse_ints(veh, 'kTriangles'),
 'vehicleFamilies': parse_ints(veh, 'kTriangleFamily'),
 'wheelPositions': parse_array(wheel, 'kPositions'),
 'wheelTriangles': parse_ints(wheel, 'kTriangles'),
 'wheelFamilies': parse_ints(wheel, 'kTriangleFamily'),
}
print({k: len(v) for k,v in data.items()})
out = pathlib.Path(__file__).resolve().parent.parent / 'src/control-vehicle-data.js'
out.write_text(
"""// GENERATED by Tools/extract-vehicle.py -- do not edit by hand.
// Source: Frontier EngineContent/GeometryArchives/ControlVehicleStructure.inl +
// ControlWheelStructure.inl (commit 319e5532d2f0f1ca59e6e5fb6997085928aadec2,
// branch arena/4f07c82a-frontier), themselves generated from ControlVehicle.blend.
// Body: 1492 verts / 2924 tris, bounds X[-3.1101,3.1101] Y[-1.2498,1.2498] Z[-0.1059,1.3516]
// (+X fwd / +Y left / +Z up). Wheel rim: 786 verts / 1568 tris, hub-local, rim radius 0.344818.
// kTriangleFamily values are DriveCourse.h CourseMaterial ids.
export const VEHICLE_POSITIONS = new Float32Array([
""" + fmt(data['vehiclePositions']) + """
]);
export const VEHICLE_TRIANGLES = new Uint32Array([
""" + fmt(data['vehicleTriangles']) + """
]);
export const VEHICLE_FAMILIES = new Uint32Array([
""" + fmt(data['vehicleFamilies']) + """
]);
export const WHEEL_POSITIONS = new Float32Array([
""" + fmt(data['wheelPositions']) + """
]);
export const WHEEL_TRIANGLES = new Uint32Array([
""" + fmt(data['wheelTriangles']) + """
]);
export const WHEEL_FAMILIES = new Uint32Array([
""" + fmt(data['wheelFamilies']) + """
]);
""")
print('wrote', out, out.stat().st_size)
