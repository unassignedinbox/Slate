"""Turn edge_matrix.json and closed_form_checks.json into the markdown tables used by the report."""
import json
import sys
from collections import Counter

Matrix = json.load(open(sys.argv[1]))
Closed = json.load(open(sys.argv[2]))
Out = sys.argv[3]

Lines = []
Lines.append('# Edge matrix results (generated by summarise.py)\n')
Lines.append(f"Fillet radius {Matrix['radius']} m, chamfer setback {Matrix['setback']} m, per-command watchdog "
             f"{Matrix['watchdog_seconds']} s. One body rebuilt per trial; one edge per trial.\n")
Lines.append('| Body | Edges | Fillet accepted & valid | Fillet accepted but invalid | Fillet refused | Fillet timeout | Chamfer accepted & valid | Chamfer accepted but invalid | Chamfer refused | Chamfer timeout | Seconds |')
Lines.append('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
TotalF = Counter()
TotalC = Counter()
for Name, Body in Matrix['bodies'].items():
    Rows = Body.get('rows', [])
    F = Counter(R['fillet']['status'] for R in Rows if 'fillet' in R)
    C = Counter(R['chamfer']['status'] for R in Rows if 'chamfer' in R)
    TotalF.update(F)
    TotalC.update(C)
    if Body.get('note'):
        Lines.append(f"| {Name} | - | - | - | - | - | - | - | - | - | {Body['note']} |")
        continue
    Lines.append(f"| {Name} | {Body['edges']} | {F['accepted']} | {F['accepted-but-invalid']} | {F['refused']} | {F['timeout']} | "
                 f"{C['accepted']} | {C['accepted-but-invalid']} | {C['refused']} | {C['timeout']} | {Body.get('seconds', '')} |")
Lines.append(f"| **Total** | | {TotalF['accepted']} | {TotalF['accepted-but-invalid']} | {TotalF['refused']} | {TotalF['timeout']} | "
             f"{TotalC['accepted']} | {TotalC['accepted-but-invalid']} | {TotalC['refused']} | {TotalC['timeout']} | |")
Lines.append('')
Lines.append("Accepted-but-invalid chamfers and fillets (checked against the source body's chi and genus, and closed, manifold, oriented):")
Bad = [(N, R['edge'], Op) for N, B in Matrix['bodies'].items() for R in B.get('rows', []) for Op in ('fillet', 'chamfer')
       if R.get(Op, {}).get('status') == 'accepted-but-invalid']
Lines.append(f"- {len(Bad)} in total" + (': ' + ', '.join(f'{N} e{E} {O}' for N, E, O in Bad) if Bad else ''))
Lines.append('')
Lines.append('## Refusal reasons (distinct, with counts)\n')
Reasons = Counter()
for N, B in Matrix['bodies'].items():
    for R in B.get('rows', []):
        for Op in ('fillet', 'chamfer'):
            X = R.get(Op, {})
            if X.get('status') == 'refused':
                Reasons[X['refusal'][-1] if X.get('refusal') else 'no reason given'] += 1
            if X.get('status') == 'timeout':
                Reasons['[watchdog] ' + X.get('detail', 'timeout')] += 1
for Text, Count in Reasons.most_common():
    Lines.append(f'- {Count} x `{Text}`')
Lines.append('')
Lines.append('## Closed-form volume checks (box 4 x 4 x 4)\n')
Lines.append('| Case | Parameter | Accepted | Valid | Expected volume | Measured volume | Absolute error |')
Lines.append('|---|---:|---|---|---:|---:|---:|')
for Section, Items in Closed.items():
    for I in Items:
        Param = I.get('radius', I.get('setback'))
        Measured = I.get('measured')
        Lines.append(f"| {Section} | {Param} | {I['accepted']} | {I.get('valid')} | {I['expected']:.6f} | "
                     f"{'' if Measured is None else format(Measured, '.6f')} | "
                     f"{'' if I.get('error') is None else format(I['error'], '.2e')} |")
open(Out, 'w').write('\n'.join(Lines) + '\n')
print('\n'.join(Lines))
