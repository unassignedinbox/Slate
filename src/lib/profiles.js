export function createRoad(presetId, points, id, overrides = {}) {
  const preset = ROAD_PRESETS.find((p) => p.id === presetId) || ROAD_PRESETS[0];
  return {
    id: id || `road-${crypto.randomUUID()}`,
    name: preset.name,
    type: preset.type || preset.id,
    presetId: preset.id,
    lanes: preset.lanes,
    oneWay: preset.oneWay || false,
    laneWidth: preset.laneWidth,
    median: preset.median,
    sidewalk: preset.sidewalk,
    shoulder: preset.shoulder || 0,
    ...(preset.gauge ? { gauge: preset.gauge, crossings: true, barriers: true } : {}),
    ...(isBridgePreset(preset)
      ? { deckThickness: preset.deckThickness || 0.8, structure: 'overpass' }
      : {}),
    ...(preset.bridgeStyle
      ? {
          bridgeStyle: preset.bridgeStyle,
          bridgeSupportSpacing: preset.bridgeSupportSpacing,
          ...(preset.bridgeRise ? { bridgeRise: preset.bridgeRise } : {}),
          ...(preset.bridgeTowerHeight ? { bridgeTowerHeight: preset.bridgeTowerHeight } : {}),
        }
      : {}),
    cycle: preset.cycle,
    bus: preset.bus,
    parking: preset.parking,
    speed: preset.speed,
    elevation: preset.elevation || 0,
    curbs: preset.curbs ?? preset.sidewalk > 0,
    drainage: 'none',
    drainSpacing: 30,
    crosswalkRamps: preset.sidewalk > 0,
    markings: preset.markings ?? !['railway', 'subway'].includes(preset.type || preset.id),
    lights: preset.lights ?? preset.sidewalk > 0,
    material:
      preset.material ||
      ((preset.type || preset.id) === 'path'
        ? 'paving'
        : presetId === 'railway'
          ? 'gravel'
          : 'asphalt'),
    points: points.map((p) => ({
      x: p.x,
      z: p.z,
      y: p.y ?? (p.nodeId ? 0 : preset.elevation || 0),
      ...(p.nodeId ? { nodeId: p.nodeId } : {}),
    })),
    ...overrides,
  };
}

export function laneDirection(road, side, standard = 'us') {
  const leftDriving = ['uk', 'jp', 'au'].includes(standard);
  if (road.type === 'roundabout') return leftDriving ? 1 : -1;
  if (road.oneWay) return 1;
  return leftDriving ? -side : side;
}

export function canEnterRoad(road, point, standard = 'us') {
  if (!road.oneWay && road.type !== 'roundabout') return true;
  const entry = laneDirection(road, -1, standard) === 1 ? road.points[0] : road.points.at(-1);
  return Math.hypot(entry.x - point.x, entry.z - point.z) < 0.1;
}

export function laneLayout(road) {
  if (road.type === 'path')
    return [{ kind: 'path', width: Math.max(0.8, road.laneWidth || 4), center: 0 }];
  if (road.type === 'railway')
    return [{ kind: 'rail', width: Math.max(1, road.lanes) * road.laneWidth, center: 0 }];
  if (road.type === 'subway') return [{ kind: 'rail', width: 6.2, center: 0 }];
  const bands = [];
  const add = (kind, width, side) => {
    if (width > 0) bands.push({ kind, width, side });
  };
  add('sidewalk', road.sidewalk, -1);
  add('shoulder', road.shoulder || 0, -1);
  if (road.parking) add('parking', 2.2, -1);
  if (road.cycle) add('cycle', 1.6, -1);
  if (road.bus) add('bus', 3.2, -1);
  for (let i = 0; i < Math.ceil(road.lanes / 2); i++) add('lane', road.laneWidth, -1);
  add('median', road.median, 0);
  for (let i = 0; i < Math.floor(road.lanes / 2); i++) add('lane', road.laneWidth, 1);
  if (road.bus) add('bus', 3.2, 1);
  if (road.cycle) add('cycle', 1.6, 1);
  if (road.parking) add('parking', 2.2, 1);
  add('shoulder', road.shoulder || 0, 1);
  add('sidewalk', road.sidewalk, 1);
  const width = bands.reduce((sum, b) => sum + b.width, 0);
  let edge = -width / 2;
  return bands.map((b) => {
    const result = { ...b, center: edge + b.width / 2 };
    edge += b.width;
    return result;
  });
}

export const roadWidth = (road) => laneLayout(road).reduce((sum, band) => sum + band.width, 0);

